// 何时该差遣写在 tools.js 里 delegate 的说明中。system 是帮手自己的系统提示，接在与主模型相同的通用段落之后；
// limit 是帮手工具轮次到顶时回给它的话；started 是差遣当即回给主模型的工具结果（帮手在后台做）；
// report / failed 是帮手做完后送进主模型这一答的一条消息（与补言同一个口子），不是系统提示。
